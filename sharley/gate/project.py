"""Export a generated project as a zip anyone can drop into Claude Code: spec, visible example tests, contract, brief.
Hidden (sealed) tests are never included; the same leak scan the judge uses guards the export."""
import io
import tempfile
import zipfile
from pathlib import Path

from sharley.gate.service import publish_examples
from sharley.intake.image import validate_image
from sharley.providers.base import sniff_mime
from sharley.schemas import Spec, TestBank

EXT = {"image/jpeg": "jpg", "image/png": "png", "image/webp": "webp", "image/gif": "gif"}
STAMP = (2026, 1, 1, 0, 0, 0)  # fixed so identical inputs give identical zips

CLAUDE_MD = """# Project generated by Sharley

Implement the service described in `SPEC.md` so the example tests in `tests/` pass, then keep improving it. Sharley will judge
the result against hidden tests you cannot see, so build to the spec, not just to the examples.
{reference}
## Rules
- `SPEC.md` is the source of truth. Cite the requirement IDs (R1, R2...) a function implements in a short comment.
- Requirements marked ASSUMED were inferred, not stated: implement them, then list them back to the user to confirm.
- Never edit, delete or skip anything in `tests/`; Sharley detects that and rejects the submission.
- Contract (`sharley.yaml`): FastAPI app at `app/main.py` exposing `app`, run with `uvicorn app.main:app --port 8000`,
  `GET /health` returns 200. Use only the standard library, fastapi, uvicorn, httpx and pydantic (the sandbox has no network).
- Treat security requirements as seriously as functional ones: auth on every non-public route, ownership checks, input validation,
  parameterised SQL, no stack traces or secrets in responses.

## Run the example tests
```
uvicorn app.main:app --port 8000 &
BASE_URL=http://localhost:8000 python -m pytest tests -q
```

## Done means
All example tests pass, every requirement in `SPEC.md` is implemented, and you have listed any ASSUMED requirements you chose to keep.
Then ask the user to run Sharley's hidden tests: `sharley check --bank-file sealed.json --workspace . ...`.
"""

PROMPT_MD = """Read CLAUDE.md, SPEC.md and tests/. First, in 10 lines, give me your plan: modules, data model, and which requirement IDs each
covers, and list every ASSUMED requirement you will implement. Then build the service, run the example tests, and show me the output.
"""


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def render_spec_md(spec: Spec) -> str:
    lines = ["# Requirements", "", f"Spec hash {spec.spec_hash[:12]}, coverage {spec.coverage_pct}%. Requirement IDs are stable.", "",
             "| ID | Category | Evidence | Requirement |", "|---|---|---|---|"]
    for r in spec.requirements:
        ev = r.evidence
        tag = "stated" if ev.kind == "observed" else f"ASSUMED ({ev.assumption_id})"
        lines.append(f"| {r.id} | {r.category} | {tag} | {_cell(r.text)} |")
    if spec.assumptions:
        lines += ["", "## Assumptions (inferred, not stated: confirm or reject)", ""]
        lines += [f"- **{k}**: {_cell(v)}" for k, v in spec.assumptions.items()]
    return "\n".join(lines) + "\n"


def build_project_zip(spec: Spec, bank: TestBank, image: bytes | None = None) -> bytes:
    """Zip of: tests/ (visible examples only), sharley.yaml, SHARLEY.md, SPEC.md, spec.json, CLAUDE.md, PROMPT.md, reference image."""
    with tempfile.TemporaryDirectory(prefix="sharley-export-") as tmp:
        root = Path(tmp)
        publish_examples(bank, spec, root)  # writes examples + contract + brief and raises LeakError if anything sealed leaked
        ref = ""
        if image is not None:
            data = validate_image(image)
            name = f"reference/photo.{EXT.get(sniff_mime(data), 'png')}"
            (root / name).parent.mkdir(parents=True, exist_ok=True)
            (root / name).write_bytes(data)
            ref = f"\nThe original photo of the idea is `{name}`: look at it for intent the text may have missed.\n"
        (root / "SPEC.md").write_text(render_spec_md(spec))
        (root / "spec.json").write_text(spec.model_dump_json(indent=2))
        (root / "CLAUDE.md").write_text(CLAUDE_MD.format(reference=ref))
        (root / "PROMPT.md").write_text(PROMPT_MD)
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
            for p in sorted(root.rglob("*")):
                if p.is_file():
                    info = zipfile.ZipInfo(p.relative_to(root).as_posix(), STAMP)
                    info.external_attr = 0o644 << 16
                    z.writestr(info, p.read_bytes())
        return buf.getvalue()
